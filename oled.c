#include "ti_msp_dl_config.h"
#include "oled.h"
#include <string.h>

#define OLED_ADDR7  0x3C
#define OLED_CMD    0x00
#define OLED_DAT    0x40
#define OLED_I2C_TO 100000U

static volatile uint8_t g_err;

static int i2c_send(const uint8_t *buf, uint16_t len)
{
    uint32_t to = OLED_I2C_TO;
    uint32_t status;

    while (!(DL_I2C_getControllerStatus(I2C_OLED_INST) &
             DL_I2C_CONTROLLER_STATUS_IDLE)) {
        if (--to == 0U) { g_err = 1U; return -1; }
    }

    /* 启动前必须先把数据写入发送缓冲 */
    DL_I2C_flushControllerTXFIFO(I2C_OLED_INST);
    if (DL_I2C_fillControllerTXFIFO(I2C_OLED_INST, buf, len) != len) {
        g_err = 4U;
        return -4;
    }

    DL_I2C_startControllerTransfer(I2C_OLED_INST, OLED_ADDR7,
        DL_I2C_CONTROLLER_DIRECTION_TX, len);

    /* 添加3个时钟周期，规避I2C错误13 */
    delay_cycles(3U);

    to = OLED_I2C_TO;
    do {
        status = DL_I2C_getControllerStatus(I2C_OLED_INST);
        if (status & DL_I2C_CONTROLLER_STATUS_ERROR) {
            g_err = 3U;
            return -3;
        }
        if (!(status & DL_I2C_CONTROLLER_STATUS_BUSY)) break;
        if (--to == 0U) { g_err = 2U; return -2; }
    } while (1);

    return 0;
}

static int OLED_SendCmd(uint8_t cmd) {
    uint8_t buf[2] = {OLED_CMD, cmd};
    return i2c_send(buf, 2);
}
static void OLED_Send(uint8_t *data, uint8_t len) {
    uint8_t offset = 0U;
    while (offset < len) {
        uint8_t chunk = (uint8_t)(len - offset);
        if (chunk > 6U) chunk = 6U;
        uint8_t buf[7];
        buf[0] = OLED_DAT;
        memcpy(&buf[1], &data[offset], chunk);
        if (i2c_send(buf, (uint16_t)(chunk + 1U)) != 0) return;
        offset = (uint8_t)(offset + chunk);
    }
}
static void OLED_SetPos(uint8_t page, uint8_t col) {
    OLED_SendCmd(0xB0 | page);
    OLED_SendCmd(0x00 | (col & 0x0F));
    OLED_SendCmd(0x10 | (col >> 4));
}

