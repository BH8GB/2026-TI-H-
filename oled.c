int OLED_Init(void)
{
    delay_cycles(16000000);
    g_err = 0U;
    static const uint8_t cmds[] = {
        0xAE,0x20,0x02,0xB0,0xC8,0x00,0x10,0x40,
        0x81,0xFF,0xA1,0xA6,0xA8,0x3F,0xA4,
        0xD3,0x00,0xD5,0xF0,0xD9,0x22,0xDA,0x12,
        0xDB,0x20,0x8D,0x14,0xAF
    };
    for (uint32_t i = 0U; i < sizeof(cmds); i++) {
        if (OLED_SendCmd(cmds[i]) != 0) return -1;
    }
    return 0;
}

void OLED_Clear(void) {
    uint8_t zero[128] = {0};
    for (uint8_t p = 0; p < 8; p++) { OLED_SetPos(p,0); OLED_Send(zero,128); }
}
void OLED_ShowChar(uint8_t page, uint8_t col, char c) {
    if (col > 121) return;
    OLED_SetPos(page, col);
    uint8_t buf[6];
    if (c >= ' ' && c <= 'z') memcpy(buf, F6x8[c - ' '], 6);
    else memcpy(buf, F6x8[0], 6);
    OLED_Send(buf, 6);
}
void OLED_ShowString(uint8_t page, uint8_t col, const char *str) {
    uint8_t pixels[126];
    uint8_t len = 0U;
    while (*str && col + len <= 121U && len <= 120U) {
        const uint8_t *glyph = F6x8[0];
        char c = *str++;
        if (c >= ' ' && c <= 'z') glyph = F6x8[c - ' '];
        memcpy(&pixels[len], glyph, 6U);
        len = (uint8_t)(len + 6U);
    }
    if (len != 0U) {
        OLED_SetPos(page, col);
        OLED_Send(pixels, len);
    }
}
